function defaultTimeline(lead) {
  const base = new Date(lead.createdAt)
  const add = (mins, label, description) => {
    const t = new Date(base.getTime() + mins * 60000)
    return {
      id: `${lead.id}-${label}`,
      label,
      description,
      time: t.toLocaleTimeString('en-US', {
        hour: 'numeric',
        minute: '2-digit',
      }),
      at: t.toISOString(),
    }
  }

  const items = [
    add(0, 'Lead Created', 'Lead entered AutoFlow'),
    add(
      0,
      'Lead Classified',
      lead.pipelineType === 'MODEL31'
        ? 'Classification: MODEL31_LEAD · Model 31 pipeline'
        : 'Classification: DEALERSHIP_LEAD · Dealership pipeline',
    ),
  ]
  if (lead.status !== 'NEW') {
    items.push(add(1, 'Conversation Started', 'AI conversation opened'))
    items.push(add(3, 'Budget Captured', `Budget set to ${lead.budget}`))
  }
  if (['QUALIFIED', 'ROUTED', 'CLOSED'].includes(lead.status)) {
    items.push(add(4, 'Vehicle Captured', lead.vehicle))
    items.push(add(5, 'Timeline Captured', lead.timeline))
    items.push(add(6, 'Lead Qualified', `Score ${lead.score} · Tier ${scoreToTier(lead.score)}`))
  }
  if (['ROUTED', 'CLOSED'].includes(lead.status)) {
    items.push(
      add(7, 'Lead Routed', `Assigned to ${lead.salesperson || 'sales team'}`),
    )
    items.push(add(8, 'CRM Sync', 'Lead synchronized to connected CRM'))
  }
  if (lead.status === 'CLOSED') {
    items.push(add(20, 'Lead Closed', 'Deal marked closed'))
  }
  return items
}

function defaultActivity(lead) {
  return [
    {
      id: `${lead.id}-act-1`,
      description: 'Lead created',
      actor: 'System',
      time: 'Just after creation',
      at: lead.createdAt,
    },
  ]
}

export const initialLeads = seed.map((lead) => {
  const classified = classifyLead(lead)
  const tier = scoreToTier(classified.score)
  const created = new Date(classified.createdAt)
  return {
    ...classified,
    tier,
    aiPaused: false,
    scoreBreakdown: breakdownFromScore(classified.score),
    createdLabel: created.toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    }),
    notes: [],
    timelineEvents: defaultTimeline({ ...classified, tier }),
    activity: defaultActivity(classified),
  }
})

