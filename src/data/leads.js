function breakdownFromScore(score) {
  const base = Math.floor(score / 5)
  const rem = score - base * 5
  const parts = [base, base, base, base, base]
  for (let i = 0; i < rem; i += 1) parts[i] += 1
  return {
    budget: Math.min(20, parts[0]),
    vehicle: Math.min(20, parts[1]),
    timeline: Math.min(20, parts[2]),
    location: Math.min(20, parts[3]),
    financing: Math.min(20, parts[4]),
  }
}

