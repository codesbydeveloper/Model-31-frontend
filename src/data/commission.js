export const COMMISSION_RATE = 0.025
export const COMMISSION_BONUS = 500
export const QUALIFYING_DEAL_MIN = 35000

export const COMMISSION_STATUSES = ['PENDING', 'APPROVED', 'PAID']

export function calculateCommission(dealAmount, rate = COMMISSION_RATE, bonus = COMMISSION_BONUS) {
  const amount = Number(dealAmount) || 0
  const baseCommission = Math.round(amount * rate)
  const appliedBonus = amount >= QUALIFYING_DEAL_MIN ? bonus : 0
  const totalCommission = baseCommission + appliedBonus
  return {
    dealAmount: amount,
    commissionRate: rate,
    baseCommission,
    bonus: appliedBonus,
    totalCommission,
  }
}

